"""Air passes: the leg goes up to meet a ball that is already in the air (after a flick, a lob, a knock-down). Run: python moves_air.py
The ball is independent in the game, so one pass card has two versions: the normal ground pass (card animation) and one of these, chosen from the ball's height when it is
played. Three contact heights: low (knee), mid (waist), high (chest). The body reaches for the ball; the free arms balance; the standing foot hops at the highest one."""
import sys
import numpy as np
import moves as M
from moves import kick_base
import moves_shot as S
from moves_shot import frame, arms_out, fly, run_pose_at

SPECS = {
    'low':  dict(label='Air Pass Low', z=11.0, lean=-0.05, hop=0.0),
    'mid':  dict(label='Air Pass Mid', z=20.0, lean=-0.22, hop=0.0),
    'high': dict(label='Air Pass High', z=30.0, lean=-0.5, hop=2.6),
}


def air_pass(kind):
    sp = SPECS[kind]; z = sp['z']; ln = sp['lean']; hop = sp['hop']
    m = kick_base()
    for f in range(8, 22): m.keys[f] = {}
    frame(m, 8, R=(2.2, -2.0, 40, 5.0), L=(-2.4, 1.0, 5, 8.0), root_y=0.4, pz=25.2, cpitch=0.1)
    frame(m, 9, R=(2.4, -3.0, 40, 6.0 + z * 0.2), L=(-3.6, 3.6, -6), root_y=1.2, pz=24.6 + hop * 0.3, cpitch=ln * 0.4, croll=-0.1 * z / 20.0)
    frame(m, 10, R=(2.8, -2.0, 45, 8.0 + z * 0.4), L=(-3.8, 4.4, -6 if hop == 0 else 10, None if hop == 0 else 3.0), root_y=2.0, pz=24.4 + hop * 0.7, cpitch=ln * 0.8, ppitch=ln * 0.4, croll=-0.2 * z / 20.0)
    frame(m, 11, R=(2.8, 3.0, 45, 8.0 + z * 0.8), L=(-3.8, 4.6, -6 if hop == 0 else 14, None if hop == 0 else 5.0), root_y=2.4, pz=24.4 + hop, cpitch=ln, ppitch=ln * 0.5, croll=-0.3 * z / 20.0)
    frame(m, 12, R=(2.8, 8.2, 42, z + 1.1, -0.9, 0.5), L=(-3.8, 4.8, -6 if hop == 0 else 16, None if hop == 0 else 6.0), root_y=2.8, pz=24.4 + hop * 1.1, cpitch=ln, ppitch=ln * 0.5, croll=-0.32 * z / 20.0, hpitch=0.35)   # contact up in the air
    frame(m, 13, R=(2.4, 12.4, 36, z + 2.0), L=(-3.6, 5.0, -6 if hop == 0 else 12, None if hop == 0 else 4.0), root_y=3.8, pz=24.4 + hop * 0.6, cpitch=ln * 0.7, croll=-0.2 * z / 20.0)
    frame(m, 14, R=(2.0, 13.4, 30, z * 0.7), L=(-3.4, 5.6, 10, 3.0 if hop else 4.0), root_y=5.4, pz=24.6, cpitch=ln * 0.3, croll=-0.1)
    frame(m, 15, R=(1.8, 12.5, 20, z * 0.3), L=(-3.0, 6.4, 12, 4.0), root_y=7.4, pz=24.4, cpitch=0.1)
    frame(m, 16, R=(2.0, 12.0, 8, None), L=(-2.6, 8.0, 15, 6.0), root_y=9.6, pz=24.2, cpitch=0.12)
    for f in range(17, 22): m.keys[f] = run_pose_at(f, 11.6, step=2.0)
    for f in (10, 11, 12): arms_out(m, f, (0.2, 1.0 + z / 60.0, 0.9, 0.9), (0.4, 1.2 + z / 60.0, 1.2, 1.0))
    arms_out(m, 13, (0.5, 0.9, 0.9, 0.7), (0.9, 1.0, 1.3, 0.8))
    c = M.aim_ball(m, 12, 'boot', 'R', vin=(0.0, -0.9, -2.0), pre=12, off=(0, 1.6, 0.4))
    m.ball(13, fly(c, (0.0, 6.0, 0.3), 9, g=0.04), spin_x=1.8)
    m.events = {'strike': 12}
    return m


def build():
    out = []
    for k, sp in SPECS.items():
        name = 'air_pass_' + k
        air_pass(k).save(name, sp['label'], 'ball already in the air: the leg meets it at z=%g. Chosen by the game from the ball height; auto-generated by sprites/moves_air.py' % sp['z']); out.append(name)
    return out


if __name__ == '__main__':
    for n in build(): print(n)
